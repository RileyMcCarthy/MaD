#include "HAL_lock.h"
#include <propeller2.h>
/**********************************************************************
 * Public Function Definitions
 **********************************************************************/

int32_t HAL_lock_create(void)
{
    return _locknew();
}

bool HAL_lock_try(int32_t lock)
{
    return _locktry(lock);
}

void HAL_lock_release(int32_t lock)
{
    _lockrel(lock);
}
